    public void filterProductStatistic() throws ParseException {
        ArrayList<ProductStatistics> stas = new ArrayList<>();
        if (jDateChooserFromPr.getDate() != null || jDateChooserToPr.getDate() != null) {
            Date from = new Date();
            Date to = new Date();
            if (jDateChooserFromPr.getDate() != null && jDateChooserToPr.getDate() == null) {
                from = jDateChooserFromPr.getDate();
                to = new Date();
            } else if (jDateChooserToPr.getDate() != null && jDateChooserFromPr.getDate() == null) {
                String sDate1 = "01/01/2022";
                from = ConvertDate.getInstance().ChangeFrom(new SimpleDateFormat("dd/MM/yyyy").parse(sDate1));
                to = jDateChooserToPr.getDate();
            } else {
                from = jDateChooserFromPr.getDate();
                to = jDateChooserToPr.getDate();
                if (from.getTime() > to.getTime()) {
                    JOptionPane.showMessageDialog(this, "Invalid Date!", "Warning", JOptionPane.WARNING_MESSAGE);
                    jDateChooserFromPr.setCalendar(null);
                    jDateChooserToPr.setCalendar(null);
                }
            }
            stas = StatisticsDAO.getInstance().getStatistics(from, to);

        } else {
            stas = StatisticsDAO.getInstance().getStatistics();
        }
        if (!txtNamePr.getText().equals("")) {
            stas = searchProductNameStatistic(stas, txtNamePr.getText());
        }
        loadDataToTableThongKeProduct(stas);
    }

    private void loadDataToTableThongKeProduct(ArrayList<ProductStatistics> stas) {
        try {
            DefaultTableModel tblModelAcc = (DefaultTableModel) tblThongKeProduct.getModel();
            tblModelAcc.setRowCount(0);
            for (int i = 0; i < stas.size(); i++) {
                tblModelAcc.addRow(new Object[]{
                    (i + 1), stas.get(i).getProductId(), stas.get(i).getProductName(), stas.get(i).getImportQuantity(), stas.get(i).getExportQuantity()
                });
            }
            tblThongKeProduct.getColumnModel().getColumn(2).setPreferredWidth(400);
        } catch (Exception e) {
        }
    }

    private ArrayList<ProductStatistics> searchProductNameStatistic(ArrayList<ProductStatistics> arr, String name) {
        ArrayList<ProductStatistics> result = new ArrayList<>();
        for (ProductStatistics i : arr) {
            if (i.getProductId().toLowerCase().contains(name.toLowerCase()) || i.getProductName().toLowerCase().contains(name.toLowerCase())) {
                result.add(i);
            }
        }
        return result;
    }

    private void loadMonthlyStatistics() {
        try {
            List<MonthlyStatisticsDAO.MonthlyData> monthlyStats = MonthlyStatisticsDAO.getInstance().getMonthlyStatistics();

            // Set the monthly statistics table model to tblPhieuNhap
            tblPhieuNhap.setModel(monthlyStatsTableModel);

            // Load data to table
            monthlyStatsTableModel.setRowCount(0);
            for (MonthlyStatisticsDAO.MonthlyData stat : monthlyStats) {
                monthlyStatsTableModel.addRow(new Object[]{
                    stat.getMonthName(),
                    formatter.format(stat.getExpense()) + "đ",
                    formatter.format(stat.getRevenue()) + "đ",
                    formatter.format(stat.getProfit()) + "đ"
                });
            }

            createBarChart(monthlyStats);

        } catch (Exception e) {
            e.printStackTrace();
        }
    }

    private void createBarChart(List<MonthlyStatisticsDAO.MonthlyData> monthlyData) {
        DefaultCategoryDataset dataset = new DefaultCategoryDataset();

        for (MonthlyStatisticsDAO.MonthlyData data : monthlyData) {
            dataset.addValue(data.getExpense(), "Import", data.getMonthName());
            dataset.addValue(data.getRevenue(), "Export", data.getMonthName());
            dataset.addValue(data.getProfit(), "Profit", data.getMonthName());
        }

        JFreeChart chart = ChartFactory.createBarChart(
            "Monthly Financial Statistics",
            "", 
            "",  
            dataset,
            PlotOrientation.VERTICAL,
            true, true, false
        );

        chart.setBackgroundPaint(new Color(248, 249, 250)); 

        CategoryPlot plot = chart.getCategoryPlot();

        plot.setBackgroundPaint(new Color(253, 253, 253)); 
        plot.setDomainGridlinePaint(new Color(230, 230, 230)); 
        plot.setRangeGridlinePaint(new Color(180, 180, 180)); 

        BarRenderer renderer = (BarRenderer) plot.getRenderer();
        renderer.setSeriesPaint(0, new Color(255, 99, 132)); 
        renderer.setSeriesPaint(1, new Color(54, 162, 235)); 
        renderer.setSeriesPaint(2, new Color(75, 192, 192)); 

        NumberAxis yAxis = (NumberAxis) plot.getRangeAxis();
        yAxis.setStandardTickUnits(NumberAxis.createIntegerTickUnits());
        yAxis.setAutoRangeIncludesZero(true);

        DecimalFormat numberFormat = new DecimalFormat("###,###,###");
        yAxis.setNumberFormatOverride(numberFormat);

        // Set font for Y-axis (range axis)
        java.awt.Font segoeUIFont = new java.awt.Font("Segoe UI", java.awt.Font.PLAIN, 12);
        yAxis.setTickLabelFont(segoeUIFont);

        // Set font for X-axis (category axis)
        org.jfree.chart.axis.CategoryAxis xAxis = plot.getDomainAxis();
        xAxis.setTickLabelFont(segoeUIFont);

        // Set font for chart title
        chart.getTitle().setFont(new java.awt.Font("Segoe UI", java.awt.Font.BOLD, 16));

        // Set font for legend
        chart.getLegend().setItemFont(segoeUIFont);

        ChartPanel chartPanelComponent = new ChartPanel(chart);
        chartPanelComponent.setPreferredSize(new Dimension(800, 300));

        chartPanel.removeAll();
        chartPanel.add(chartPanelComponent, BorderLayout.CENTER);
        chartPanel.revalidate();
        chartPanel.repaint();
    }

