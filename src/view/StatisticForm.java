    private void setupYearSpinner() {
        Calendar calendar = Calendar.getInstance();
        int currentYear = calendar.get(Calendar.YEAR);

        SpinnerNumberModel yearModel = new SpinnerNumberModel(
            currentYear,
            2000,
            2100,
            1
        );

        jSpinner1.setModel(yearModel);

        javax.swing.JSpinner.NumberEditor editor = new javax.swing.JSpinner.NumberEditor(jSpinner1, "#");
        jSpinner1.setEditor(editor);

        // Disable text cursor blinking in spinner
        javax.swing.JFormattedTextField textField = editor.getTextField();
        textField.setEditable(false);
        textField.setFocusable(false);

        jSpinner1.addChangeListener(e -> {
            int selectedYear = (Integer) jSpinner1.getValue();
            loadMonthlyStatisticsForYear(selectedYear);
        });
    }

   
    private void loadMonthlyStatisticsForYear(int year) {
        try {
            // Get monthly statistics data for the selected year
            List<MonthlyStatisticsDAO.MonthlyData> monthlyStats =
                MonthlyStatisticsDAO.getInstance().getMonthlyStatistics(year);

            // Set the monthly statistics table model to tblPhieuNhap
            tblPhieuNhap.setModel(monthlyStatsTableModel);

            // Clear and load data to table
            monthlyStatsTableModel.setRowCount(0);
            for (MonthlyStatisticsDAO.MonthlyData stat : monthlyStats) {
                monthlyStatsTableModel.addRow(new Object[]{
                    stat.getMonthName(),
                    formatter.format(stat.getExpense()) + "đ",
                    formatter.format(stat.getRevenue()) + "đ",
                    formatter.format(stat.getProfit()) + "đ"
                });
            }

            // Update the existing chart with new data for the selected year
            updateChartForYear(monthlyStats, year);

            System.out.println("Loaded Monthly Financial Statistics for year: " + year);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                "Error loading monthly statistics for year " + year + ": " + e.getMessage(),
                "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    /**
     * Update existing chart with new year data or show message if chart not available
     */
    private void updateChartForYear(List<MonthlyStatisticsDAO.MonthlyData> monthlyData, int year) {
        try {
            createBarChart(monthlyData);
        } catch (Exception e) {
            System.out.println("Chart update failed, showing table data only for year: " + year);
        }
    }
